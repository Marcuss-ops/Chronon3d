// ── Mirror of the backend's GpuGlyphStatic / GpuTextRunDynamic (std430) ──
struct GpuGlyphStatic {
    std::uint32_t run_index;
    std::uint32_t atlas_page_and_flags; // low 16: page, high 16: flags (bit0 = MTSDF)
    std::uint32_t atlas_pos;            // low 16: x, high 16: y
    std::uint32_t atlas_size;           // low 16: w, high 16: h
    float plane_left;
    float plane_top;
    float plane_right;
    float plane_bottom;
    std::uint32_t draw_order;
    std::uint32_t pad0;
    std::uint32_t pad1;
    std::uint32_t pad2;
};
static_assert(sizeof(GpuGlyphStatic) == 48);

struct GpuGlyphDynamic {
    float tracking_prefix;
    float selector_weight;
};
static_assert(sizeof(GpuGlyphDynamic) == 8);

// Use the production ABI directly.  The shader consumes the extended
// selector/animator block (112 bytes, std430 stride); a hand-written 64-byte
// mirror silently made every default-initialized glyph invisible and caused
// the second run to be read at the wrong array stride.
using GpuTextRunDynamic = chronon3d::runtime::TextRunDynamic;
static_assert(sizeof(GpuTextRunDynamic) == 112);
static_assert(alignof(GpuTextRunDynamic) == 16);

