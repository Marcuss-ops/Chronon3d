// ── Minimal headless device context ─────────────────────────────────────
struct DeviceContext {
    VkInstance instance{VK_NULL_HANDLE};
    VkPhysicalDevice physical{VK_NULL_HANDLE};
    VkDevice device{VK_NULL_HANDLE};
    VkQueue queue{VK_NULL_HANDLE};
    std::uint32_t queue_family{0};
    bool ok() const { return device != VK_NULL_HANDLE; }
};

DeviceContext make_device() {
    DeviceContext ctx;
    const VkApplicationInfo app{
        VK_STRUCTURE_TYPE_APPLICATION_INFO, nullptr, "Chronon3D text tile canary",
        VK_MAKE_VERSION(1, 0, 0), "Chronon3D", VK_MAKE_VERSION(1, 0, 0),
        VK_API_VERSION_1_1};
    const VkInstanceCreateInfo info{
        VK_STRUCTURE_TYPE_INSTANCE_CREATE_INFO, nullptr, 0, &app, 0, nullptr, 0, nullptr};
    if (vkCreateInstance(&info, nullptr, &ctx.instance) != VK_SUCCESS) return ctx;

    std::uint32_t count = 0;
    if (vkEnumeratePhysicalDevices(ctx.instance, &count, nullptr) != VK_SUCCESS || count == 0) {
        return ctx;
    }
    std::vector<VkPhysicalDevice> devices(count);
    vkEnumeratePhysicalDevices(ctx.instance, &count, devices.data());

    for (const auto pd : devices) {
        std::uint32_t fam_count = 0;
        vkGetPhysicalDeviceQueueFamilyProperties(pd, &fam_count, nullptr);
        std::vector<VkQueueFamilyProperties> fams(fam_count);
        vkGetPhysicalDeviceQueueFamilyProperties(pd, &fam_count, fams.data());
        for (std::uint32_t f = 0; f < fam_count; ++f) {
            if ((fams[f].queueFlags & VK_QUEUE_COMPUTE_BIT) != 0) {
                ctx.physical = pd;
                ctx.queue_family = f;
                break;
            }
        }
        if (ctx.physical != VK_NULL_HANDLE) break;
    }
    if (ctx.physical == VK_NULL_HANDLE) return ctx;

    constexpr float priority = 1.0f;
    const VkDeviceQueueCreateInfo queue{
        VK_STRUCTURE_TYPE_DEVICE_QUEUE_CREATE_INFO, nullptr, 0,
        ctx.queue_family, 1, &priority};
    const VkDeviceCreateInfo dev{
        VK_STRUCTURE_TYPE_DEVICE_CREATE_INFO, nullptr, 0, 1, &queue,
        0, nullptr, 0, nullptr, nullptr};
    if (vkCreateDevice(ctx.physical, &dev, nullptr, &ctx.device) != VK_SUCCESS) {
        ctx.device = VK_NULL_HANDLE;
        return ctx;
    }
    vkGetDeviceQueue(ctx.device, ctx.queue_family, 0, &ctx.queue);
    return ctx;
}

void destroy(DeviceContext& ctx) {
    if (ctx.device) vkDestroyDevice(ctx.device, nullptr);
    if (ctx.instance) vkDestroyInstance(ctx.instance, nullptr);
}

bool format_supports_storage(VkPhysicalDevice pd, VkFormat format) {
    VkFormatProperties props{};
    vkGetPhysicalDeviceFormatProperties(pd, format, &props);
    return (props.optimalTilingFeatures & VK_FORMAT_FEATURE_STORAGE_IMAGE_BIT) != 0;
}

std::uint32_t find_memory(VkPhysicalDevice pd, std::uint32_t type_bits,
                          VkMemoryPropertyFlags wanted) {
    VkPhysicalDeviceMemoryProperties mem{};
    vkGetPhysicalDeviceMemoryProperties(pd, &mem);
    for (std::uint32_t i = 0; i < mem.memoryTypeCount; ++i) {
        if ((type_bits & (1u << i)) != 0 &&
            (mem.memoryTypes[i].propertyFlags & wanted) == wanted) {
            return i;
        }
    }
    return UINT32_MAX;
}

struct Buffer {
    VkDevice device{VK_NULL_HANDLE};
    VkBuffer handle{VK_NULL_HANDLE};
    VkDeviceMemory memory{VK_NULL_HANDLE};
    void* mapped{nullptr};
    VkDeviceSize size{0};

    void destroy() {
        if (handle) vkDestroyBuffer(device, handle, nullptr);
        if (memory) vkFreeMemory(device, memory, nullptr);
        handle = VK_NULL_HANDLE;
        memory = VK_NULL_HANDLE;
    }
};

Buffer make_host_buffer(VkDevice device, VkPhysicalDevice pd, VkDeviceSize size) {
    Buffer b;
    b.device = device;
    b.size = size;
    const VkBufferCreateInfo info{
        VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO, nullptr, 0, size,
        VK_BUFFER_USAGE_STORAGE_BUFFER_BIT | VK_BUFFER_USAGE_TRANSFER_DST_BIT,
        VK_SHARING_MODE_EXCLUSIVE};
    REQUIRE(vkCreateBuffer(device, &info, nullptr, &b.handle) == VK_SUCCESS);
    VkMemoryRequirements req{};
    vkGetBufferMemoryRequirements(device, b.handle, &req);
    const auto type = find_memory(pd, req.memoryTypeBits,
                                  VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT |
                                      VK_MEMORY_PROPERTY_HOST_COHERENT_BIT);
    REQUIRE(type != UINT32_MAX);
    const VkMemoryAllocateInfo alloc{
        VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO, nullptr, req.size, type};
    REQUIRE(vkAllocateMemory(device, &alloc, nullptr, &b.memory) == VK_SUCCESS);
    REQUIRE(vkBindBufferMemory(device, b.handle, b.memory, 0) == VK_SUCCESS);
    REQUIRE(vkMapMemory(device, b.memory, 0, size, 0, &b.mapped) == VK_SUCCESS);
    return b;
}

struct Image {
    VkDevice device{VK_NULL_HANDLE};
    VkImage handle{VK_NULL_HANDLE};
    VkDeviceMemory memory{VK_NULL_HANDLE};
    VkImageView view{VK_NULL_HANDLE};
    VkFormat format{VK_FORMAT_UNDEFINED};
    std::uint32_t width{0};
    std::uint32_t height{0};

    void destroy() {
        if (view) vkDestroyImageView(device, view, nullptr);
        if (handle) vkDestroyImage(device, handle, nullptr);
        if (memory) vkFreeMemory(device, memory, nullptr);
        handle = VK_NULL_HANDLE;
        memory = VK_NULL_HANDLE;
    }
};

Image make_storage_image(VkDevice device, VkPhysicalDevice pd, std::uint32_t w,
                         std::uint32_t h, VkFormat format) {
    Image img;
    img.device = device;
    img.format = format;
    img.width = w;
    img.height = h;
    const VkImageCreateInfo info{
        VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO, nullptr, 0, VK_IMAGE_TYPE_2D,
        format, {w, h, 1}, 1, 1, VK_SAMPLE_COUNT_1_BIT, VK_IMAGE_TILING_OPTIMAL,
        VK_IMAGE_USAGE_TRANSFER_DST_BIT | VK_IMAGE_USAGE_TRANSFER_SRC_BIT |
            VK_IMAGE_USAGE_STORAGE_BIT,
        VK_SHARING_MODE_EXCLUSIVE, VK_IMAGE_LAYOUT_UNDEFINED};
    REQUIRE(vkCreateImage(device, &info, nullptr, &img.handle) == VK_SUCCESS);
    VkMemoryRequirements req{};
    vkGetImageMemoryRequirements(device, img.handle, &req);
    const auto type = find_memory(pd, req.memoryTypeBits,
                                  VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT);
    REQUIRE(type != UINT32_MAX);
    const VkMemoryAllocateInfo alloc{
        VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO, nullptr, req.size, type};
    REQUIRE(vkAllocateMemory(device, &alloc, nullptr, &img.memory) == VK_SUCCESS);
    REQUIRE(vkBindImageMemory(device, img.handle, img.memory, 0) == VK_SUCCESS);
    const VkImageViewCreateInfo view{
        VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO, nullptr, 0, img.handle,
        VK_IMAGE_VIEW_TYPE_2D, format, {VK_COMPONENT_SWIZZLE_IDENTITY,
            VK_COMPONENT_SWIZZLE_IDENTITY, VK_COMPONENT_SWIZZLE_IDENTITY,
            VK_COMPONENT_SWIZZLE_IDENTITY},
        {VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1}};
    REQUIRE(vkCreateImageView(device, &view, nullptr, &img.view) == VK_SUCCESS);
    return img;
}

