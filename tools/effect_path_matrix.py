#!/usr/bin/env python3
"""Generate docs/reference/effect-path-matrix.md.

Sources (all authoritative, nothing hand-maintained):
  * include/chronon3d/effects/effect_catalog.def   -> every effect, id, params type
  * include/chronon3d/render_graph/effect_gpu_capability.hpp -> Vulkan native routes
  * src/backends/software/processors/**            -> CPU processor registrations
  * src/**/cuda* and include/**/cuda*             -> CUDA references (by enum name)

Columns:
  CPU     : a processor is registered for the effect's params type
  Vulkan  : NativeZeroReadback route in kGpuEffectCapabilityRows, else Unsupported
  CUDA    : the enum name is referenced by a CUDA source file

Use --check to fail (exit 1) when the committed matrix is stale.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "include/chronon3d/effects/effect_catalog.def"
CAPABILITY = ROOT / "include/chronon3d/render_graph/effect_gpu_capability.hpp"
SOFTWARE = ROOT / "src/backends/software"
OUT = ROOT / "docs/reference/effect-path-matrix.md"

CATALOG_RE = re.compile(
    r"CHRONON_EFFECT\(\s*(\d+)\s*,\s*(\w+)\s*,\s*(\w+)\s*,\s*([\w:]+)\s*,\s*\"([^\"]*)\"")
NATIVE_RE = re.compile(r"\{effects::EffectType::(\w+)\s*,")
REGISTER_RE = re.compile(r"register_effect_processor<\s*(?:chronon3d::)?(\w+)\s*>")


def catalog() -> list[tuple[int, str, str, str, str]]:
    text = CATALOG.read_text(encoding="utf-8")
    return [(int(v), enum, params, ident, name) for v, enum, params, ident, name in CATALOG_RE.findall(text)]


def native_routes() -> set[str]:
    text = CAPABILITY.read_text(encoding="utf-8")
    block = text.split("kNativeRoutes", 1)[1].split("}};", 1)[0]
    return set(NATIVE_RE.findall(block))


def cpu_registered_params() -> set[str]:
    found: set[str] = set()
    for source in SOFTWARE.rglob("*.cpp"):
        found.update(REGISTER_RE.findall(source.read_text(encoding="utf-8", errors="replace")))
    return found


def cuda_referenced(enum_names: list[str]) -> set[str]:
    sources = [p for p in list((ROOT / "src").rglob("*cuda*")) + list((ROOT / "include").rglob("*cuda*"))
               if p.is_file()]
    text = "\n".join(p.read_text(encoding="utf-8", errors="replace") for p in sources)
    return {name for name in enum_names if re.search(rf"EffectType::{name}\b", text)}


def render() -> str:
    rows = catalog()
    native = native_routes()
    cpu = cpu_registered_params()
    cuda = cuda_referenced([enum for _, enum, _, _, _ in rows])
    lines = [
        "# Effect x execution path matrix",
        "",
        "Generated by `tools/effect_path_matrix.py` from `effect_catalog.def`,",
        "`effect_gpu_capability.hpp`, the software processor registrations, and CUDA",
        "sources. Do not edit by hand.",
        "",
        "| id | effect | params | CPU | Vulkan | CUDA |",
        "|---:|---|---|:-:|:-:|:-:|",
    ]
    for value, enum, params, _ident, display in rows:
        cpu_mark = "yes" if params in cpu else "no"
        vk_mark = "native" if enum in native else "unsupported"
        cuda_mark = "yes" if enum in cuda else "no"
        lines.append(f"| {value} | {display} | `{params}` | {cpu_mark} | {vk_mark} | {cuda_mark} |")
    lines += [
        "",
        f"Totals: {len(rows)} catalog effects, {sum(1 for _, e, *_ in rows if e in native)} with native Vulkan routes.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    content = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != content:
            print("effect-path-matrix.md is stale; run tools/effect_path_matrix.py")
            return 1
        print("effect-path-matrix.md is up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
