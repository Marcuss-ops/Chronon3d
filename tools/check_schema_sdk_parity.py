#!/usr/bin/env python3
"""Gate: `schemas/json/` is source; `sdk-dist/` must be generated.

sdk-dist is `cmake --install --prefix sdk-dist` output (gitignored).  If it
exists, its three schemas must be byte-identical to the source ones — any
stale hand-copied copy shows up here before it ships to an external SDK
consumer as the wrong dialect (source ≠ renderer vs SDK).
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA_SRC = ROOT / "schemas" / "json"
SDK_SCHEMAS = ROOT / "sdk-dist" / "share" / "chronon3d" / "schemas"
FILES = [
    "chronon.composition.v1.schema.json",
    "chronon.render-plan.v2.schema.json",
    "chronon.render-settings.v1.schema.json",
]


def sha(path: Path) -> str:
    h = hashlib.sha256()
    h.update(path.read_bytes())
    return h.hexdigest()[:12]


def main() -> int:
    if not SCHEMA_SRC.is_dir():
        print(f"FAIL: missing {SCHEMA_SRC}", file=sys.stderr)
        return 1

    # Source is the only truth; sdk-dist being absent is fine (not yet installed).
    if not SDK_SCHEMAS.is_dir():
        print(
            f"SDK schema parity: SKIP (no {SDK_SCHEMAS} on disk — not yet installed; "
            "source is `schemas/json/`). "
            "Run `cmake --install build/... --prefix sdk-dist` to regenerate it.",
        )
        return 0

    failures: list[str] = []
    for name in FILES:
        src = SCHEMA_SRC / name
        dst = SDK_SCHEMAS / name
        if not src.is_file() or not dst.is_file():
            failures.append(f"missing pair for {name}: have src={src.is_file()} sdk={dst.is_file()}")
            continue
        a, b = sha(src), sha(dst)
        if a != b:
            failures.append(f"drift: {name} source {a} != sdk-dist {b} — run cmake --install")

    # Extra files inside sdk-dist that aren't in source are also a drift (hand-placed stale dialect).
    sdk_only = {p.name for p in SDK_SCHEMAS.glob("*.json")} - set(FILES)
    if sdk_only:
        failures.append(f"unexpected files in sdk-dist/schemas: {sorted(sdk_only)}")

    if failures:
        for msg in failures:
            print(f"FAIL: {msg}", file=sys.stderr)
        print(
            "source is `schemas/json/`; `sdk-dist/` must be regenerated by packaging "
            "(cmake --install), never hand-copied. Fix: `cmake --install <build> --prefix sdk-dist`.",
            file=sys.stderr,
        )
        return 1

    print("SDK schema parity: PASS (schemas/json == sdk-dist/share/chronon3d/schemas).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
